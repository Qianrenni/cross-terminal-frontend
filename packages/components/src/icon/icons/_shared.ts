/**
 * 图标几何的公用辅助 —— **画布 100×100**（约定见 `./type.ts`）。
 *
 * 只放「多个图标会共用」的构造器；单个图标自己的坐标直接写在它自己的文件里，
 * 这样对着设计稿改的时候，diff 只出现在那一个文件里。
 */

/** 圆：以 `(cx, cy)` 为心、`r` 为半径的单条路径（两段弧拼成整圆）。 */
export const circle = (cx: number, cy: number, r: number) =>
  `M${cx - r} ${cy} a${r} ${r} 0 1 0 ${r * 2} 0 a${r} ${r} 0 1 0 ${-r * 2} 0`;

/**
 * 100 网格上「满格圆」的半径：四周各留 13 的边距。
 *
 * 这样即使最粗的描边（`bold` = 12）也不会顶到画布边界：`13 - 12 / 2 = 7 > 0`。
 */
export const RING_RADIUS = 37;

/** 居中的圆圈描边路径（直径 74）。`info` / `error` 这类图标复用它。 */
export const RING = circle(50, 50, RING_RADIUS);
