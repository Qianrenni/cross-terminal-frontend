import type { IconShape } from './type';

/**
 * 占位框（`placeholder-line`）：**虚线圆角矩形**，线性风格。
 *
 * ## 为什么拆成两条路径
 *
 * 虚线是沿**整条路径**连续铺下去的。如果把「四条直边 + 四个圆角」写成一条 `d`，
 * 虚线段会跨过圆角把它切成两半，圆角看起来就成了被斜切的角、而不是一段弧。
 * 所以这里拆开：
 *
 * - `stroke`（虚线）：四条直边，每条 44 长
 * - `solidStroke`（实线）：四个角的四分之一圆，半径 14，**各一整段不间断**
 *
 * ## 几何
 *
 * 外接 `14 → 86`（边长 72，沿用 `square` 的尺寸），圆角半径 14（约占边长 19%）。
 * 半径一开始给的是 18（25%），渲染出来「八边形感」压过「框感」；14 与 iOS 那个比例接近，
 * 框感才出来。
 *
 * ## 为什么粗细是 thin、虚线是 `[8, 14]`
 *
 * 直边只有 44 长，而渲染层固定用 `strokeLinecap="round"`：圆头会让每段虚线两端各向外
 * 「长」出 `strokeWidth / 2`、同时吃掉同样多的空隙。
 * regular（8）下空隙至少被吃掉 8，44 上根本排不下第二段虚线；而且 8/100 在 20px 下是 1.6px，
 * 比圆角本身还粗，弧的弯曲也就看不出来了。降到 thin（5）之后：
 * `dash: [8, 14]` → 视觉 **虚线 13 / 空隙 9**，每条边正好 2 段。
 *
 * `8 + 14 = 22`，而 `44 / 22 = 2` **整除**，所以四条边各自对称、接缝处不会留半截虚线
 * （整条路径 176 也是 8 个周期，即便实现上不按子路径重置虚线也一样匀）。
 *
 * ⚠️ `weight` prop 可以覆盖：一旦改成 `bold`（12），视觉空隙只剩 `14 − 12 = 2`，会糊成实线，
 * 别在这个图标上用粗档。
 */
const placeholderLine: IconShape = {
  // 四条直边：虚线，每条正好 2 段
  stroke: 'M28 14 H72 M86 28 V72 M72 86 H28 M14 72 V28',
  dash: [8, 14],
  // 四个角：各一整段不间断的四分之一圆弧
  solidStroke:
    'M14 28 A14 14 0 0 1 28 14 M72 14 A14 14 0 0 1 86 28 M86 72 A14 14 0 0 1 72 86 M28 86 A14 14 0 0 1 14 72',
  weight: 'thin',
};

export default placeholderLine;
